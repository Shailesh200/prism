/**
 * Generate the reference pages that would otherwise rot (M-038 Phase 4).
 *
 * The CLI command table and the MCP tool registry already exist in code, and
 * they are the *only* description of those surfaces that cannot be wrong. Hand
 * copying them into Markdown guarantees the docs describe a Prism that no
 * longer exists a few milestones later, so these pages are generated instead.
 *
 *   bun run scripts/generate-docs-reference.mjs          write the pages
 *   bun run scripts/generate-docs-reference.mjs --check  fail if stale
 *
 * `--check` runs in verification, which is what makes this a guarantee rather
 * than a habit.
 */

import { readFile, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const repoRoot = join(dirname(fileURLToPath(import.meta.url)), "..");
const docsDir = join(repoRoot, "docs", "reference");

const BANNER = `<!-- Generated by scripts/generate-docs-reference.mjs. Do not edit by hand. -->`;

/**
 * Workspace packages are not linked into the root `node_modules`, so import the
 * build output directly. Anything else would need a dependency edge from the
 * repository root onto two surfaces, which is worse than a path.
 */
async function loadBuilt(pkg) {
  const entry = join(repoRoot, "packages", pkg, "dist", "index.js");
  try {
    return await import(pathToFileURL(entry).href);
  } catch (cause) {
    throw new Error(
      `generate-docs-reference: cannot load @repo-prism/${pkg} from ${entry}. ` +
        `Run \`bun run build\` first.`,
      { cause },
    );
  }
}

/** Markdown table cell escaping: only the pipe can break a table. */
function cell(text) {
  return String(text).replaceAll("|", "\\|");
}

/**
 * Tool titles are just the name in title case, which makes for a summary column
 * that repeats the first column. The opening sentence of the description is
 * what a reader actually scans the table for.
 */
function firstSentence(text) {
  const match = /^(.+?[.:])\s/s.exec(String(text));
  return (match ? match[1] : String(text)).replace(/[.:]$/, "");
}

async function cliCommandsPage() {
  const { COMMANDS, COMMAND_GROUPS } = await loadBuilt("cli");

  const lines = [
    "---",
    "title: CLI commands",
    'description: "Every Prism CLI subcommand, generated from the command table the binary is built from."',
    "---",
    "",
    BANNER,
    "",
    "Every `prism` command, generated from the command table the binary is built",
    "from. If a command appears here, it exists; if its options are listed here,",
    "they are the options it accepts.",
    "",
    "See [Using the CLI](../cli/usage.md) for global options, exit codes, and how",
    "`--fail-on` behaves in CI.",
    "",
  ];

  for (const group of COMMAND_GROUPS) {
    const inGroup = COMMANDS.filter((command) => command.group === group);
    if (inGroup.length === 0) continue;

    lines.push(`## ${group}`, "");
    for (const command of inGroup) {
      const args = (command.arguments ?? [])
        .map((argument) => argument.syntax)
        .join(" ");
      lines.push(
        `### \`prism ${command.name}${args ? ` ${args}` : ""}\``,
        "",
        command.summary,
        "",
      );

      if ((command.arguments ?? []).length > 0) {
        lines.push("| Argument | Meaning |", "|---|---|");
        for (const argument of command.arguments ?? []) {
          lines.push(
            `| \`${cell(argument.syntax)}\` | ${cell(argument.description)} |`,
          );
        }
        lines.push("");
      }

      if ((command.options ?? []).length > 0) {
        lines.push("| Option | Meaning |", "|---|---|");
        for (const option of command.options ?? []) {
          lines.push(
            `| \`${cell(option.flags)}\` | ${cell(option.description)} |`,
          );
        }
        lines.push("");
      }

      for (const example of command.examples ?? []) {
        lines.push("```bash", example, "```", "");
      }
    }
  }

  return `${lines.join("\n").trimEnd()}\n`;
}

async function loadMcpTools() {
  const { TOOLS, DISPATCH_TOOLS } = await loadBuilt("mcp-server");
  return [...TOOLS, ...DISPATCH_TOOLS];
}

async function mcpToolsPage() {
  const allTools = await loadMcpTools();

  const lines = [
    "---",
    "title: MCP tools",
    'description: "Every tool the Prism MCP server exposes, generated from the tool registry."',
    "---",
    "",
    BANNER,
    "",
    "Every tool the Prism MCP server exposes, generated from the tool registry",
    "the server is built from.",
    "",
    "Intelligence tools are read-only Core adapters. Dispatch tools (jobs, OAuth,",
    "memory, configure) write gitignored state under `.prism/dispatch/` and do not",
    "index. Completing OAuth in the browser is the human grant for Dispatch drivers.",
    "Core analysis APIs stay ungated from MCP. See",
    "[Consent and privacy](../concepts/consent-and-privacy.md) and",
    "[Dispatch](../mcp/dispatch.md).",
    "",
    "Tools that return a list accept `limit` and answer with `totalCount` and",
    "`truncated`, so an agent can tell the first 20 of 340 from all 20 there are.",
    "",
    "| Tool | What it answers |",
    "|---|---|",
  ];

  for (const tool of allTools.toSorted((a, b) =>
    a.name.localeCompare(b.name),
  )) {
    lines.push(
      `| [\`${cell(tool.name)}\`](#${tool.name}) | ${cell(firstSentence(tool.description))} |`,
    );
  }

  lines.push("");

  for (const tool of allTools.toSorted((a, b) =>
    a.name.localeCompare(b.name),
  )) {
    lines.push(`## \`${tool.name}\``, "", tool.description, "");
    const keys = Object.keys(tool.inputSchema ?? {});
    lines.push(
      keys.length === 0
        ? "Takes no arguments."
        : `Arguments: ${keys.map((key) => `\`${key}\``).join(", ")}.`,
      "",
    );
  }

  return `${lines.join("\n").trimEnd()}\n`;
}

async function capabilitiesPage() {
  const { COMMANDS } = await loadBuilt("cli");
  const allTools = await loadMcpTools();

  const lines = [
    "---",
    "title: Capabilities",
    'description: "One row per Prism capability — CLI command, MCP tool, and what question it answers."',
    "---",
    "",
    BANNER,
    "",
    "Lookup table generated from the CLI command table and MCP tool registry.",
    "Prefer the [guides](../guides/understand-a-repo.mdx) when you have a job to do;",
    "use this page when you need the exhaustive index.",
    "",
    "## CLI",
    "",
    "| Command | What it answers |",
    "|---|---|",
  ];

  for (const command of COMMANDS.toSorted((a, b) =>
    a.name.localeCompare(b.name),
  )) {
    lines.push(
      `| \`prism ${cell(command.name)}\` | ${cell(firstSentence(command.description ?? command.name))} |`,
    );
  }

  lines.push("", "## MCP tools", "", "| Tool | What it answers |", "|---|---|");

  for (const tool of allTools.toSorted((a, b) =>
    a.name.localeCompare(b.name),
  )) {
    lines.push(
      `| \`${cell(tool.name)}\` | ${cell(firstSentence(tool.description))} |`,
    );
  }

  lines.push("");
  return `${lines.join("\n").trimEnd()}\n`;
}

const PAGES = [
  ["cli-commands.md", cliCommandsPage],
  ["mcp-tools.md", mcpToolsPage],
  ["capabilities.md", capabilitiesPage],
];

const check = process.argv.includes("--check");
let stale = 0;

for (const [name, build] of PAGES) {
  const path = join(docsDir, name);
  const next = await build();

  if (!check) {
    await writeFile(path, next, "utf8");
    console.log(`generate-docs-reference: wrote docs/reference/${name}`);
    continue;
  }

  const current = await readFile(path, "utf8").catch(() => null);
  if (current !== next) {
    stale += 1;
    console.error(
      current === null
        ? `generate-docs-reference: docs/reference/${name} is missing`
        : `generate-docs-reference: docs/reference/${name} is stale`,
    );
  }
}

if (check) {
  if (stale > 0) {
    console.error(
      "generate-docs-reference: run `bun run docs:reference` and commit the result",
    );
    process.exitCode = 1;
  } else {
    console.log(`generate-docs-reference: ok (${PAGES.length} pages current)`);
  }
}
