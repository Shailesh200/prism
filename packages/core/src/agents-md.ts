import type { AgentsMdClaims } from "@repo-prism/shared";

const CLAIMS_OPEN = "<!-- prism:agents-md-claims";
const CLAIMS_CLOSE = "-->";

/**
 * Deterministic AGENTS.md content (M-073 C1): prose composed from
 * `dependency_cycles` and test-file paths, plus a
 * machine-readable claims block `--check` re-verifies against a fresh
 * index. No LLM prose — every line here traces to an Iris query.
 */
export function buildAgentsMdContent(input: {
  readonly generatedAt: string;
  readonly cycles: readonly (readonly string[])[];
  readonly testFiles: readonly string[];
}): string {
  const lines: string[] = [];
  lines.push("# AGENTS.md (generated by Prism — do not edit by hand)");
  lines.push("");
  lines.push(
    `Generated ${input.generatedAt}. Regenerate with \`prism agents-md generate\`; verify with \`prism agents-md --check\`.`,
  );
  lines.push("");

  lines.push("## Import boundaries (cycles)");
  if (input.cycles.length === 0) {
    lines.push("- No import cycles detected.");
  } else {
    for (const cycle of input.cycles) {
      lines.push(`- Cycle: ${cycle.join(" → ")}`);
    }
  }
  lines.push("");

  lines.push("## Test locations");
  if (input.testFiles.length === 0) {
    lines.push("- No test files detected.");
  } else {
    for (const path of [...input.testFiles].sort()) {
      lines.push(`- ${path}`);
    }
  }
  lines.push("");

  const claims: AgentsMdClaims = {
    generatedAt: input.generatedAt,
    cycles: input.cycles.map((c) => [...c]).sort(compareCycle),
  };
  lines.push(CLAIMS_OPEN);
  lines.push(JSON.stringify(claims));
  lines.push(CLAIMS_CLOSE);
  lines.push("");

  return lines.join("\n");
}

function compareCycle(a: readonly string[], b: readonly string[]): number {
  return a.join("\0").localeCompare(b.join("\0"));
}

/** Extracts the claims block written by `buildAgentsMdContent`, or `null`. */
export function parseAgentsMdClaims(content: string): AgentsMdClaims | null {
  const start = content.indexOf(CLAIMS_OPEN);
  if (start === -1) return null;
  const end = content.indexOf(CLAIMS_CLOSE, start);
  if (end === -1) return null;
  const raw = content.slice(start + CLAIMS_OPEN.length, end).trim();
  try {
    const parsed = JSON.parse(raw) as unknown;
    if (
      typeof parsed !== "object" ||
      parsed === null ||
      !("cycles" in parsed)
    ) {
      return null;
    }
    return parsed as AgentsMdClaims;
  } catch {
    return null;
  }
}
