const DEFAULT_ICONS = ["file", "folder", "folder-open"];

function minifySvg(svg) {
  return svg
    .replace(/<\?xml[^>]*\?>/g, "")
    .replace(/<!--[\s\S]*?-->/g, "")
    .replace(/\s*\n\s*/g, " ")
    .replace(/>\s+</g, "><")
    .trim();
}

function loadSvg(iconName) {
  const def = manifest.iconDefinitions[iconName];
  if (!def) return null;
  const rel = def.iconPath.replace(/^\.\/\.\.\//, "");
  try {
    return minifySvg(readFileSync(join(pkgRoot, rel), "utf8"));
  } catch {
    return null;
  }
}

const svgSet = {};
const folderOpen = new Set(
  FOLDER_ICONS.map((n) => `${n}-open`).concat("folder-open"),
);
const wanted = new Set([
  ...FILE_ICONS,
  ...FOLDER_ICONS,
  ...folderOpen,
  ...DEFAULT_ICONS,
]);
for (const name of wanted) {
  const svg = loadSvg(name);
  if (svg) svgSet[name] = svg;
}

const has = (name) => Object.prototype.hasOwnProperty.call(svgSet, name);

function filterMap(source) {
  const out = {};
  for (const [key, icon] of Object.entries(source ?? {})) {
    if (has(icon)) out[key.toLowerCase()] = icon;
  }
  return out;
}

const fileExtensions = filterMap(manifest.fileExtensions);
const fileNames = filterMap(manifest.fileNames);
const folderNames = filterMap(manifest.folderNames);
const folderNamesExpanded = filterMap(manifest.folderNamesExpanded);

const body = `// AUTOGENERATED by scripts/gen-material-icons.mjs — do not edit by hand.
// Source: material-icon-theme@${require("material-icon-theme/package.json").version}
/* eslint-disable */

export const MATERIAL_SVG: Record<string, string> = ${JSON.stringify(svgSet, null, 0)};

export const FILE_EXT_ICON: Record<string, string> = ${JSON.stringify(fileExtensions)};

export const FILE_NAME_ICON: Record<string, string> = ${JSON.stringify(fileNames)};

export const FOLDER_ICON: Record<string, string> = ${JSON.stringify(folderNames)};

export const FOLDER_OPEN_ICON: Record<string, string> = ${JSON.stringify(folderNamesExpanded)};

export const DEFAULT_FILE_ICON = "file";
export const DEFAULT_FOLDER_ICON = "folder";
export const DEFAULT_FOLDER_OPEN_ICON = "folder-open";
`;

